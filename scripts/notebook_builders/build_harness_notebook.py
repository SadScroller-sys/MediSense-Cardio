"import wfdb, os",
"",
"# LOCAL PATCH (same as the demo notebook): Colab's numpy removed the old",
"# np.fromstring binary-read path that wfdb's own code still calls internally.",
"import numpy as np",
"_original_fromstring = np.fromstring",
"def _patched_fromstring(string, dtype=float, count=-1, sep=''):",
"    if sep == '':",
"        return np.frombuffer(string, dtype=dtype, count=count)",
"    return _original_fromstring(string, dtype=dtype, count=count, sep=sep)",
"np.fromstring = _patched_fromstring",
"",
"os.makedirs('/content/data/pilot', exist_ok=True)",
