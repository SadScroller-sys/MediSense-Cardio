"""Section Z (EXPLORATORY, SIMULATION): the straightening fix and the traffic light on 120 SIMULATED phone photos of the pages G021-G080.
Rules fixed BEFORE any photo existed: docs/plan/analysis_plan_changes.md, 2026-11-14 (evening). Refuses to run twice.
  python -I scripts/analysis/section_Z_sim_photos.py
Primary (one test): V2 (straightened) against V0 (photo as it is) on the 120 photos; bad = no usable heart rate OR wrong (> 5 bpm, cleaned measure; reference = PTB-XL 100 Hz lead II, same code);
exact McNemar test, alpha 0.05; 'confirmed in simulation' only if bad falls AND p < 0.05. Everything else is descriptive."""
import os
import sys
import warnings

import numpy as np
import pandas as pd
from scipy.stats import binomtest

warnings.filterwarnings("ignore")
ROOT = "D:/Capstone Project/"
SIM = ROOT + "results/fresh_sim/"
OUT = ROOT + "results/analysis/"
sys.path.insert(0, ROOT + "safeguard")
import ecg_traffic_light as T  # noqa: E402


def hr_clean(sig, fs=1000):
    import neurokit2 as nk
    x = nk.ecg_clean(sig, sampling_rate=fs, method="neurokit")
    p, _ = nk.ecg_peaks(x, sampling_rate=fs)
    return float(np.nanmean(nk.ecg_rate(p, sampling_rate=fs, desired_length=len(sig))))


def wilson(k, n, z=1.96):
    if n == 0:
        return "n/a"
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{k}/{n} ({100 * p:.0f}%, 95% CI {100 * (c - h):.0f}-{100 * (c + h):.0f}%)"


def md(t):
    h = "| " + " | ".join(map(str, t.columns)) + " |\n|" + "---|" * len(t.columns) + "\n"
    return h + "\n".join("| " + " | ".join(str(z) for z in r) + " |" for r in t.itertuples(index=False))


if __name__ == "__main__":
    out_csv = OUT + "sectionZ_all.csv"
    if os.path.exists(out_csv) and "--force" not in sys.argv:
        sys.exit("The test was already run once (rule: run ONCE).")
    import wfdb
    meta = pd.read_csv(SIM + "photos_meta.csv")
    log = pd.read_csv(SIM + "digitise_log.csv")
    found = log[log.variant == "v2"].set_index("photo").page_found.to_dict()
    assert len(meta) == 120
    ref = {}
    for pg in sorted(meta.page.unique()):
        rec = wfdb.rdrecord(SIM.replace("fresh_sim", "fresh_g") + f"source_records/{pg}")
        ref[pg] = hr_clean(rec.p_signal[:, rec.sig_name.index("II")], rec.fs)
    rows = []
    for m in meta.itertuples():
        for variant in ("v0", "v2"):
            path = SIM + f"dig_{variant}/{m.photo}.npz"
            if not os.path.exists(path):
                sys.exit(f"missing {path}: digitising is not finished")
            z = T.load_npz(path)
            s = np.asarray(z["II"], float)
            s = s[np.isfinite(s)] / 1000.0
            try:
                hr = hr_clean(s) if len(s) > 10 else np.nan
            except Exception:
                hr = np.nan
            rows.append(dict(photo=m.photo, page=m.page, shot=m.shot, extra=m.extra, variant=variant, page_found=(found.get(m.photo) if variant == "v2" else np.nan),
                             dig_hr=hr, gt_hr=ref[m.page], light=T.check(z)["light"]))
    d = pd.DataFrame(rows)
    d["none"] = d.dig_hr.isna()
    d["wrong"] = ~d.none & ((d.dig_hr - d.gt_hr).abs() > 5)
    d["bad"] = d.none | d.wrong
    d.to_csv(out_csv, index=False)
    b0 = d[d.variant == "v0"].set_index("photo").bad
    b2 = d[d.variant == "v2"].set_index("photo").bad.reindex(b0.index)
    worse, better = int((b2 & ~b0).sum()), int((~b2 & b0).sum())
    p = binomtest(worse, worse + better, 0.5).pvalue if worse + better else 1.0
    verdict = "confirmed in simulation" if (b2.sum() < b0.sum() and p < 0.05) else "not confirmed"
    prim = pd.DataFrame([dict(bad_original_v0=int(b0.sum()), bad_straightened_v2=int(b2.sum()), newly_bad=worse, newly_good=better, p_exact=round(p, 5), verdict=verdict)])
    summ = d.groupby("variant").agg(photos=("bad", "size"), no_usable_hr=("none", "sum"), wrong=("wrong", "sum"), bad=("bad", "sum")).reset_index()
    by_shot = d.groupby(["variant", "shot"]).agg(photos=("bad", "size"), bad=("bad", "sum")).reset_index()
    by_extra = d.groupby(["variant", "extra"]).agg(photos=("bad", "size"), bad=("bad", "sum")).reset_index()
    lights = []
    for v in ("v0", "v2"):
        x = d[d.variant == v]
        for lt in ("GREEN", "AMBER", "RED"):
            y = x[x.light == lt]
            lights.append(dict(variant=v, light=lt, photos=len(y), no_usable_hr=int(y.none.sum()), wrong=int(y.wrong.sum()), bad=wilson(int(y.bad.sum()), len(y))))
    lights = pd.DataFrame(lights)
    pf = d[d.variant == "v2"].page_found.astype(str).value_counts().to_dict()
    L = ["# Section Z: straightening and the traffic light on 120 SIMULATED phone photos (EXPLORATORY, simulation)", "",
         "*Generated by `scripts/analysis/section_Z_sim_photos.py`. Rules fixed before any photo existed (docs/plan/analysis_plan_changes.md, 2026-11-14 evening). Photos are a SIMULATION made by `make_sim_photos.py` (seed 49): "
         "pages G021-G080, 2 photos per page (straight, angled), tilt, screen edge, vignette, noise, and on random photos blur, shadow or a smaller page. bad = no usable heart rate or wrong (> 5 bpm, cleaned measure). "
         "Intervals treat photos as independent (two photos of a page are not).*", "",
         "## Primary: V2 (straightened) against V0 (photo as it is), exact paired test", "", md(prim), "", "## Both variants", "", md(summ), "", "## By shot", "", md(by_shot), "",
         "## By extra", "", md(by_extra), "", "## Traffic lights (frozen safeguard, not retrained)", "", md(lights), "", f"Page finder on V2 (page_found): {pf}", ""]
    open(OUT + "SECTION_Z.md", "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))
